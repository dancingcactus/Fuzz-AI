"""Write the demo's memory (js/demo-memory.js and the Knowledge files in assets/samples/) from the real core.

The inspector's demo mode reads what the core's own inspector returns, so its shapes can't drift from the
endpoints. The store is the first-week fixture (core/tests/fixtures/memory_week1.json) put through the scripted
extractor (as `fuzz run extractor --scripted` does) on the tests' clock, the morning before the Staff sync, so a brief is written too.

    PYTHONPATH=core ~/.local/share/uv/tools/fuzz-core/bin/python core/scripts/make_demo_memory.py

Run it again after a change to the fixture or to what the inspector returns; the output is the same each time.
"""

import json
import os
import shutil
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "core"))
sys.path.insert(0, os.path.join(ROOT, "core", "tests"))

from helpers import Clock  # noqa: E402

from fuzz import config  # noqa: E402
from fuzz.db import Core  # noqa: E402
from fuzz.memory import briefs, inspect  # noqa: E402
from fuzz.runner import run_role  # noqa: E402

FIXTURE = os.path.join(ROOT, "core", "tests", "fixtures", "memory_week1.json")
SAMPLES = os.path.join(ROOT, "assets", "samples")
OUT = os.path.join(ROOT, "js", "demo-memory.js")


def main():
    home = tempfile.mkdtemp()
    try:
        cfg = config.load(home)
        cfg["me"] = {"names": ["Justin"], "emails": ["justin@acme.example"], "slack_ids": ["WEXAMPLE1"]}
        cfg["embedder"] = "hash"
        cfg["tz"] = "UTC"
        config.save(home, cfg)
        core = Core(home, 1, clock=Clock())
        with open(FIXTURE) as f:
            run_role(core, "extractor", None, None, None, True, False, "manual", json.load(f))
        briefs.write_all(core)
        data, files = snapshot(core)
        core.close()
    finally:
        shutil.rmtree(home, True)
    text = json.dumps(data, indent=1, sort_keys=True, ensure_ascii=False)
    if home in text:
        raise SystemExit("a path from the temporary store is still in the snapshot")
    with open(OUT, "w") as f:
        f.write("/* Fuzz's memory for the demo: what the core's inspector returns for the first-week fixture.\n"
                "   Generated by core/scripts/make_demo_memory.py; don't edit by hand. js/memory.js reads it when\n"
                "   there's no core. */\nwindow.DemoMemory = " + text + ";\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)} and {len(files)} Knowledge files in assets/samples/")


def snapshot(core):
    """Every inspector answer the demo can give, with the Knowledge files moved to assets/samples/."""
    files = {}   # memory_files id -> the demo sample it became

    def sample(f):
        if f["id"] not in files:
            name = os.path.basename(f["path"])
            shutil.copyfile(f["path"], os.path.join(SAMPLES, name))
            files[f["id"]] = {"id": f"memory-{f['id']}", "name": name, "kind": f["kind"],
                              "size": os.path.getsize(f["path"])}
        s = files[f["id"]]
        return dict(f, path=s["name"], url="artifact.html?demo=" + s["id"])

    st = inspect.briefs_state(core)
    st["files"] = [sample(f) for f in st["files"]]
    for m in st["meetings"]:
        if m["file"]:
            m["file"] = sample(m["file"])
    ents = inspect.entities_list(core)
    ids = [e["id"] for e in ents["entities"]]
    runs = inspect.runs_list(core)
    return {
        "overview": inspect.overview(core),
        "entities": ents,
        "entity": {str(i): inspect.entity_detail(core, i) for i in ids},
        "why_not": {f"{a}-{b}": inspect.why_not(core, a, b) for a in ids for b in ids if a != b},
        "knowledge": inspect.knowledge_list(core),
        "decisions": inspect.decisions_list(core),
        "runs": runs,
        "run": {str(r["id"]): inspect.run_detail(core, r["id"]) for r in runs["runs"]},
        "briefs": st,
        "files": sorted(files.values(), key=lambda s: s["id"]),
    }, files


if __name__ == "__main__":
    main()
