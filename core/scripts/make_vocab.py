"""Write js/vocab.js: the names the core accepts, for the UI and its tests.

The browser can't import Python, so the core's names (task states, card kinds and their answers, the task
verbs) are written out as a script, the way js/demo-memory.js is. core/tests/test_vocab.py fails when the
file is out of date, and tests/ui/vocab.test.mjs checks every name js/live.js sends is in it.

    PYTHONPATH=core ~/.local/share/uv/tools/fuzz-core/bin/python core/scripts/make_vocab.py

It describes this checkout, not the server a page talks to: what gates an answer at run time is still the
options each card comes with from GET /cards. Variant tags aren't here, since the core has no full list of
them (cards.TRIAGE_TAGS is only the ones that end when a task leaves triage).
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "core"))

from fuzz import actions, answers, cards, states  # noqa: E402
from fuzz.memory import mcards  # noqa: E402

OUT = os.path.join(ROOT, "js", "vocab.js")


def vocab():
    return {
        "states": list(states.STATES),
        "closed": list(states.CLOSED),
        "cardKinds": {name: {"family": k.family, "options": list(k.options), "suggested": k.suggested,
                             "safe": k.safe if k.postpones else None}
                      for name, k in cards.CARD_KINDS.items()},
        # every answer a task card can offer, and the lists a task's variant picks between
        "taskAnswers": sorted(answers.TASK_ANSWERS),
        "taskOptions": list(cards.TASK_OPTIONS),
        "taskVariants": {tag: list(opts) for tag, opts in cards.TASK_VARIANTS},
        "bigLead": list(cards.BIG_LEAD),
        # POST /tasks/{id}/<verb>
        "taskVerbs": list(actions.TASK_VERBS),
        # the cards Fuzz's memory raises, which have no task
        "memoryKinds": list(mcards.KINDS),
    }


def render():
    body = json.dumps(vocab(), indent=1, ensure_ascii=False)
    return ("/* The core's names: task states, card kinds and their answers, task verbs. Generated by\n"
            "   core/scripts/make_vocab.py from the core; don't edit by hand. */\n"
            f"window.FuzzVocab = {body};\n")


def main():
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(render())
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
